use duke_bytecode::decode;
use duke_classfile::{
    parse,
    types::{AttributeData, CpEntry, CpIndex},
};
use std::process;

fn cp_str(cf: &duke_classfile::ClassFile, idx: CpIndex) -> Option<&str> {
    cf.constant_pool
        .get(idx.0 as usize)
        .and_then(|slot| slot.as_ref())
        .and_then(|entry| {
            if let CpEntry::Utf8(s) = entry {
                Some(s.as_str())
            } else {
                None
            }
        })
}

// Extracted for testability
pub fn dump_search_internal(
    bytes: &[u8],
    query: &str,
    out: &mut impl std::io::Write,
) -> Result<(), String> {
    let cf = parse(bytes).map_err(|e| format!("parse error: {e}"))?;

    let query_lower = query.to_lowercase();
    let mut found_any = false;

    for method in &cf.methods {
        let name_str = cp_str(&cf, method.name_index).unwrap_or("<invalid>");
        let desc_str = cp_str(&cf, method.descriptor_index).unwrap_or("<invalid>");
        let full_name = format!("{name_str}{desc_str}");

        for attr in &method.attributes {
            if let AttributeData::Code(code) = &attr.data {
                #[allow(clippy::collapsible_if)]
                if let Ok(instructions) = decode(&code.code) {
                    let mut found_in_method = false;
                    for (pc, instr) in instructions {
                        let mnemonic = instr.mnemonic().to_lowercase();
                        if mnemonic.contains(&query_lower) {
                            if !found_in_method {
                                writeln!(out, "Method: {full_name}").map_err(|e| e.to_string())?;
                                found_in_method = true;
                                found_any = true;
                            }
                            writeln!(out, "  {pc:>4}: {mnemonic}").map_err(|e| e.to_string())?;
                        }
                    }
                    if found_in_method {
                        writeln!(out).map_err(|e| e.to_string())?;
                    }
                }
            }
        }
    }

    if !found_any {
        writeln!(out, "No instructions matching '{query}' found.").map_err(|e| e.to_string())?;
    }
    Ok(())
}

pub fn dump_search(path: &str, query: &str) {
    let bytes = std::fs::read(path).unwrap_or_else(|e| {
        eprintln!("duke: cannot read '{path}': {e}");
        process::exit(1);
    });

    let mut stdout = std::io::stdout();
    if let Err(e) = dump_search_internal(&bytes, query, &mut stdout) {
        eprintln!("duke: {e}");
        process::exit(1);
    }
}

